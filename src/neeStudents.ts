const normalize = (value: string) => value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toUpperCase().replace(/[^A-Z0-9]/g, '');
const key = (student: { name: string; escola: string; turma: string }) => [student.escola, student.turma, student.name].map(normalize).join('|');
const neeKeys = new Set(NEE_STUDENTS.map(key));

export function isNeeStudent(student: { name: string; escola: string; turma: string }): boolean {
  return neeKeys.has(key(student));
}

export function getNeeInterventionStats(students: ReadonlyArray<{ name: string; escola: string; turma: string; s1?: string }>) {
  const cohort = students.filter(student => student.s1 === 'N1' || student.s1 === 'N2');
  const nee = cohort.filter(isNeeStudent);
  return {
    total: cohort.length,
    nee: nee.length,
    percentage: cohort.length ? (nee.length / cohort.length) * 100 : 0,
    n1: nee.filter(student => student.s1 === 'N1').length,
    n2: nee.filter(student => student.s1 === 'N2').length,
  };
}
